const POST_COUNT = 96

const TITLE_LEADS = ['Notes on', 'Revisiting', 'A Field Guide to', 'Lessons from', 'Measuring', 'Rethinking', 'Debugging', 'The Case for']

const postTitles = (): string[] => {
  const titles = [...TOPICS]
  const seen = new Set(titles.map(slugify))
  const r = rng(77)
  while (titles.length < POST_COUNT) {
    const title = `${pick(r, TITLE_LEADS)} ${phrase(r, 2, 3).replace(/\b\w/g, c => c.toUpperCase())}`
    if (!seen.has(slugify(title))) {
      seen.add(slugify(title))
      titles.push(title)
    }
  }
  return titles
}

const TAGS = ['performance', 'rendering', 'architecture', 'css', 'tooling', 'react', 'effect']

const paragraph = (r: () => number) => Array.from({ length: 3 + Math.floor(r() * 3) }, () => sentence(r)).join(' ')

const makePost = (title: string, i: number): Post => {
  const r = rng(i + 1)
  const blocks: Block[] = [{ type: 'p', text: paragraph(r) }]
  for (let s = 0; s < 5; s++) {
    const heading = sentence(r, 3, 6).replace(/\.$/, '')
    blocks.push({ type: 'h2', id: `${s + 1}-${slugify(heading)}`, text: heading })
    blocks.push({ type: 'p', text: paragraph(r) })
    if (s % 2 === 0) blocks.push({ type: 'ul', items: [sentence(r, 4, 9), sentence(r, 4, 9), sentence(r, 4, 9)] })
    if (s === 1) blocks.push({ type: 'code', text: `export function ${slugify(title).replace(/-/g, '_')}() {\n  return render(model, view)\n}` })
    if (s === 3) blocks.push({ type: 'quote', text: sentence(r, 10, 16) })
    blocks.push({ type: 'p', text: paragraph(r) })
  }
  const date = new Date(Date.UTC(2026, 9, 24) - i * 6 * 86400000)
  const words = blocks.reduce((n, b) => n + JSON.stringify(b).split(' ').length, 0)
  return {
    slug: slugify(title),
    title,
    excerpt: sentence(r, 16, 24),
    date: date.toISOString().slice(0, 10),
    readingMinutes: Math.max(2, Math.round(words / 220)),
    tags: [TAGS[i % TAGS.length]!, TAGS[(i + 3) % TAGS.length]!],
    author: AUTHORS[i % AUTHORS.length]!,
    blocks,
  }
}

export const posts: Post[] = postTitles().map(makePost)

export const summarize = ({ blocks: _blocks, ...summary }: Post): PostSummary => summary

export const allPostSummaries = (): PostSummary[] => posts.map(summarize)

export const latestPostSummaries = (n = 6): PostSummary[] => allPostSummaries().slice(0, n)

export const getPost = (slug: string): Post | undefined => posts.find(p => p.slug === slug)

export const relatedPosts = (slug: string, n = 3): PostSummary[] => {
  const i = posts.findIndex(p => p.slug === slug)
  return Array.from({ length: n }, (_, k) => summarize(posts[(i + k + 1) % posts.length]!))
}

const COMMENTERS = ['jules', 'mkr', 'devon.p', 'aiko', 'rafael', 'noor', 'pip']

export const commentsFor = (slug: string): Comment[] => {
  const i = posts.findIndex(p => p.slug === slug)
  const r = rng(1000 + i)
  return Array.from({ length: 4 + (i % 4) }, (_, k) => ({
    id: `${slug}-c${k}`,
    author: COMMENTERS[(i + k) % COMMENTERS.length]!,
    date: posts[i]!.date,
    body: sentence(r, 10, 26),
  }))
}

export const postsTagged = (tag: string, n = 4): PostSummary[] =>
  allPostSummaries().filter(p => p.tags.includes(tag)).slice(0, n)

// WIDGETS

// Every widget becomes its own client component (React) or view module
// (Foldkit), generated by scripts/generate.ts. The specs are baked into that
// code, so they never travel as data.

export const WIDGET_KINDS = [
  'Stepper',
  'Switches',
  'Disclosure',
  'Segmented',
  'Rating',
  'Poll',
  'Slider',
  'Filter',
  'Carousel',
  'Checklist',
] as const
export type WidgetKind = (typeof WIDGET_KINDS)[number]

const KIND_NOUNS: Record<WidgetKind, string[]> = {
  Stepper: ['budget', 'planner', 'counter'],
  Switches: ['settings', 'flags', 'options'],
  Disclosure: ['notes', 'details', 'questions'],
  Segmented: ['modes', 'views', 'presets'],
  Rating: ['rating', 'review', 'score'],
  Poll: ['poll', 'survey', 'vote'],
  Slider: ['estimator', 'calculator', 'dial'],
  Filter: ['finder', 'index', 'lookup'],
  Carousel: ['tour', 'walkthrough', 'slides'],
  Checklist: ['checklist', 'audit', 'steps'],
}

const ITEM_COUNT: Record<WidgetKind, [number, number]> = {
  Stepper: [1, 1],
  Switches: [3, 5],
  Disclosure: [3, 5],
  Segmented: [3, 4],
  Rating: [1, 1],
  Poll: [3, 5],
  Slider: [1, 1],
  Filter: [8, 12],
  Carousel: [4, 6],
  Checklist: [4, 6],
}

export type WidgetSpec = {
  id: string
  /** Component and module name, e.g. W001EdgeCacheBudget. */
  component: string
  kind: WidgetKind
  title: string
  items: { label: string; detail: string }[]
  min: number
  max: number
  step: number
  start: number
  factor: number
  unit: string
  votes: number[]
  hue: number
}

const UNITS = ['ms', 'KiB', 'requests', '%', 's', 'MB']

const makeWidget = (n: number): WidgetSpec => {
  const r = rng(9000 + n)
  const kind = WIDGET_KINDS[n % WIDGET_KINDS.length]!
  const title = `${capitalize(pick(r, ['edge', 'cache', 'bundle', 'route', 'stream', 'island', 'script', 'asset', 'worker', 'layout']))} ${pick(r, ['request', 'payload', 'chunk', 'token', 'module', 'latency', 'budget', 'state'])} ${pick(r, KIND_NOUNS[kind])}`
  const [low, high] = ITEM_COUNT[kind]
  const items = Array.from({ length: low + Math.floor(r() * (high - low + 1)) }, () => ({
    label: phrase(r, 1, 3),
    detail: sentence(r, 8, 14),
  }))
  const max = pick(r, [10, 20, 50, 100, 250])
  const step = max >= 100 ? 5 : 1
  return {
    id: `w${String(n + 1).padStart(3, '0')}`,
    component: `W${String(n + 1).padStart(3, '0')}${title.replace(/(^|\s)(\w)/g, (_, _s, c: string) => c.toUpperCase())}`,
    kind,
    title,
    items,
    min: step,
    max,
    step,
    start: step * (1 + Math.floor((r() * max) / step / 2)),
    factor: Math.round((1 + r() * 9) * 10) / 10,
    unit: pick(r, UNITS),
    votes: items.map(() => 5 + Math.floor(r() * 55)),
    hue: Math.floor(r() * 360),
  }
}

// GENERATED PAGES

export type FeaturePage = {
  section: string
  slug: string
  title: string
  tagline: string
  /** Widget ids in render order. */
  widgets: string[]
  paragraphs: string[]
}

const { pagesPerSection, sharedWidgetsPerSection, sharedWidgetsPerPage, uniqueWidgetsPerPage } = scale

export const widgetSpecs: WidgetSpec[] = Array.from(
  { length: sections.length * (sharedWidgetsPerSection + pagesPerSection * uniqueWidgetsPerPage) },
  (_, n) => makeWidget(n),
)

const makeFeaturePage = (sectionIndex: number, pageIndex: number, taken: Set<string>): FeaturePage => {
  const r = rng(20000 + sectionIndex * 1000 + pageIndex)
  let title = phrase(r, 2, 3)
  while (taken.has(slugify(title))) title = phrase(r, 2, 3)
  taken.add(slugify(title))
  const shared = Array.from(
    { length: sharedWidgetsPerPage },
    (_, k) => sectionIndex * sharedWidgetsPerSection + ((pageIndex + k) % sharedWidgetsPerSection),
  )
  const firstUnique = sections.length * sharedWidgetsPerSection + (sectionIndex * pagesPerSection + pageIndex) * uniqueWidgetsPerPage
  const order = Array.from({ length: uniqueWidgetsPerPage }, (_, k) => firstUnique + k)
  // Spread the section's shared widgets through the page.
  shared.forEach((n, k) => order.splice(Math.floor(((k + 1) * order.length) / (shared.length + 1)) + k, 0, n))
  return {
    section: sections[sectionIndex]!.slug,
    slug: slugify(title),
    title,
    tagline: sentence(r, 10, 16),
    widgets: order.map(n => widgetSpecs[n]!.id),
    paragraphs: Array.from({ length: order.length + 1 }, () => paragraph(r)),
  }
}

export const featurePages: FeaturePage[] = sections.flatMap((_, si) => {
  const taken = new Set<string>()
  return Array.from({ length: pagesPerSection }, (_, pi) => makeFeaturePage(si, pi, taken))
})

const featureHref = (page: FeaturePage) => `/${page.section}/${page.slug}`

// ROUTE DATA

export const homeData = (): HomeData => ({ latest: latestPostSummaries(), byTopic: homeTopics.map(t => postsTagged(t)) })

export const blogData = (): BlogData => ({ posts: allPostSummaries() })

export const postData = (slug: string): PostData | undefined => {
  const post = getPost(slug)
  return post && { post, related: relatedPosts(slug), comments: commentsFor(slug) }
}

export const sectionData = (slug: string): SectionData | undefined => {
  const section = sections.find(s => s.slug === slug)
  return (
    section && {
      section,
      pages: featurePages
        .filter(p => p.section === slug)
        .map(p => ({ title: p.title, href: featureHref(p), tagline: p.tagline })),
    }
  )
}

export const featureData = (section: string, slug: string): FeatureData | undefined => {
  const page = featurePages.find(p => p.section === section && p.slug === slug)
  const meta = sections.find(s => s.slug === section)
  return (
    page &&
    meta && {
      section: { slug: meta.slug, title: meta.title },
      href: featureHref(page),
      title: page.title,
      tagline: page.tagline,
      paragraphs: page.paragraphs,
      siblings: featurePages.filter(p => p.section === section).map(p => ({ title: p.title, href: featureHref(p) })),
    }
  )
}

