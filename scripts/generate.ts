//
// The same ten kinds as ReScript components for Xote. Reactive text is a
// thunk, and a conditional that starts out empty is an explicit
// View.tracked block (see apps/xote/src/Ui.res).

type XoteTemplate = { constants: string; state: string; body: string }

const res = (value: unknown) => JSON.stringify(value)
const resItems = (w: WidgetSpec) =>
  `[${w.items.map(i => `{label: ${res(i.label)}, detail: ${res(i.detail)}}`).join(', ')}]`
const resFloat = (n: number) => (Number.isInteger(n) ? `${n}.` : String(n))

